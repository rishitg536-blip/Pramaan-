import { describe, it, expect } from 'vitest';
import { buildFingerprintFile } from '../src/core/fingerprint';
import { appendEntry } from '../src/core/custody';
import * as fs from 'fs';
import * as path from 'path';
import { execSync } from 'child_process';

describe('Python Standalone Verifier (verify_pramaan.py)', () => {
  it('successfully verifies a fingerprint file generated by Pramaan core', async () => {
    // 1. Build a test case
    const files = [
      {
        id: 'f1',
        order: 1,
        name: 'test_evidence.txt',
        size: 100,
        mimeType: 'text/plain',
        lastModified: 1700000000000,
        sha256: 'a1b2c3d4e5f6a1b2c3d4e5f6a1b2c3d4e5f6a1b2c3d4e5f6a1b2c3d4e5f6a1b2',
        leaf: '',
        addedAt: new Date().toISOString(),
      },
      {
        id: 'f2',
        order: 2,
        name: 'screenshot.png',
        size: 5000,
        mimeType: 'image/png',
        lastModified: 1700000001000,
        sha256: 'b2c3d4e5f6a1b2c3d4e5f6a1b2c3d4e5f6a1b2c3d4e5f6a1b2c3d4e5f6a1b2c3',
        leaf: '',
        addedAt: new Date().toISOString(),
      },
    ];

    const logEntry0 = await appendEntry([], 'CASE_CREATED', { title: 'Test Case' }, null, '2026-08-10T10:00:00.000Z');
    const logEntry1 = await appendEntry([logEntry0], 'FILE_ADDED', { name: 'test_evidence.txt' }, 'f1', '2026-08-10T10:01:00.000Z');
    const logEntry2 = await appendEntry([logEntry0, logEntry1], 'FILE_ADDED', { name: 'screenshot.png' }, 'f2', '2026-08-10T10:02:00.000Z');

    const fpFile = await buildFingerprintFile({
      caseId: 'TEST-CASE-001',
      sealedAt: '2026-08-10T10:05:00.000Z',
      files,
      custodyLog: [logEntry0, logEntry1, logEntry2],
    });

    const tmpJsonPath = path.resolve(__dirname, 'test-fingerprint.json');
    fs.writeFileSync(tmpJsonPath, JSON.stringify(fpFile, null, 2), 'utf8');

    try {
      const scriptPath = path.resolve(__dirname, '../verify_pramaan.py');
      try {
        const output = execSync(`python "${scriptPath}" "${tmpJsonPath}"`, { encoding: 'utf8' });
        expect(output).toContain('[OK] ALL CRYPTOGRAPHIC CHECKS PASSED');
      } catch (err: any) {
        console.error('Python stdout:', err.stdout);
        console.error('Python stderr:', err.stderr);
        throw err;
      }
    } finally {
      if (fs.existsSync(tmpJsonPath)) {
        fs.unlinkSync(tmpJsonPath);
      }
    }
  });
});
